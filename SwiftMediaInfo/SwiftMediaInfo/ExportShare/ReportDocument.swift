    --button-bg: #ffffff; --button-border: #d9d4f2;
    """
    
    /// Same structure, lifted for a dark page: text and accents brightened
    /// until they read at the same contrast as the light version.
    private static let pdfDark = """
    --ink: #ececf4; --ink2: #a4a4bc; --rule: #2d2d3f; --zebra: #1b1b27;
    --video: #6cb4ff; --audio: #b48cff; --text: #5fd49a; --image: #4fd6e8;
