//
//  ReportDocument.swift
//  SwiftMediaInfo
//
//  The Markdown and PDF exports' content (the PDF's HTML is printed by
//  PDFRenderer).
//
//  Both are written for people, not parsers, so they share one shape:
//
//    1. The file — name, then size · duration · container.
//    2. Highlights — the colour-coded chips from the Easy View overview.
//    3. Overview — the Media Summary (video, audio, subtitles, image, tags).
//    4. Tracks — every stream, with the same readable fields Easy View shows.
//    5. Where it came from — app, version, date, website and GitHub.
//
//  Built from the parsed tracks and the shared MediaSummary, so the reports
//  agree with the overview card field for field. MediaInfo's internal names
//  never appear: every label goes through FieldFormat.friendlyLabel.
//

import Foundation
import AppKit

struct ReportDocument {

    struct Section {
        let title: String
        /// The track type whose colour the section uses.
        let trackType: String
        let rows: [MarkdownBuilder.Row]
    }

    let fileName: String
    let summary: MediaSummary
    let trackSections: [Section]
    let generated: Date

    init(file: MediaFile, generated: Date = Date()) {
        fileName = file.url.lastPathComponent
        summary = MediaSummary(tracks: file.tracks, fileURL: file.url)
        self.generated = generated

        trackSections = file.tracks.compactMap { track -> Section? in
            var rows = EasyFields.resolve(for: track).map { field -> MarkdownBuilder.Row in
                // MediaInfo's FileName has no extension; the report shows the
                // whole name, as Easy View does.
                let value = field.key == "FileName" ? file.url.lastPathComponent : field.value
                return (FieldFormat.friendlyLabel(field.key), value)
            }
            if track.type == "General", let digest = track.value(for: FileHasher.fieldKey) {
                rows.append(("SHA-256", digest))
            }
            guard !rows.isEmpty else { return nil }
            return Section(title: track.displayTitle, trackType: track.type, rows: rows)
        }
    }

    // MARK: Shared details

    static var appVersion: String {
        Bundle.main.object(forInfoDictionaryKey: "CFBundleShortVersionString") as? String ?? ""
    }

    /// The app's page without its trailing slash, as it is printed.
    static let websiteText = "undisclosed0369.app/swiftmediainfo"
    static let githubText = "github.com/Undisclosed0369/SwiftMediaInfo"

    private var dateText: String {
        generated.formatted(date: .long, time: .shortened)
    }

    /// The overview's sections, minus File (it is the report's heading).
    private var overviewSections: [MediaSummary.Section] {
        summary.sections.filter { $0.trackType != "General" }
    }

    // MARK: - Markdown

    var markdown: String {
        var parts: [String] = []

        parts.append(MarkdownBuilder.heading(fileName, level: 1))

        if !summary.fileDetails.isEmpty {
            parts.append("**" + MarkdownBuilder.inline(summary.fileDetails.joined(separator: " · ")) + "**")
        }

        let highlights = summary.chipGroups.map { group in
            "**\(Self.groupName(group.trackType))** " + group.chips.map { "`\($0)`" }.joined(separator: " ")
        }
        if !highlights.isEmpty {
            parts.append("> " + highlights.joined(separator: " &nbsp;·&nbsp; "))
        }

        if !overviewSections.isEmpty {
            parts.append(MarkdownBuilder.heading("Overview", level: 2))
            for section in overviewSections {
                parts.append(MarkdownBuilder.section(section.title, rows: section.rows.map { ($0.label, Self.shortened($0)) }))
            }
        }

        if !trackSections.isEmpty {
            parts.append(MarkdownBuilder.heading("Tracks", level: 2))
            for section in trackSections {
                let isChapters = section.trackType == "Menu"
                parts.append(
                    MarkdownBuilder.heading(section.title, level: 3) + "\n\n"
                    + MarkdownBuilder.table(rows: section.rows, headers: isChapters ? ("Time", "Chapter") : ("Field", "Value"))
                )
            }
        }

        parts.append("---")
        let version = Self.appVersion.isEmpty ? "" : " \(Self.appVersion)"
        parts.append(
            "Generated by [SwiftMediaInfo](\(ProjectLinks.appPage))\(version) on \(dateText) · "
            + "[GitHub](\(ProjectLinks.github))"
        )

        return parts.joined(separator: "\n\n") + "\n"
    }

    private static func groupName(_ trackType: String) -> String {
        switch trackType {
        case "Video": return "Video"
        case "Audio": return "Audio"
        case "Text":  return "Subtitles"
        case "Image": return "Image"
        default:      return trackType
        }
    }

    // MARK: - PDF (as HTML, rendered by PDFRenderer)

    /// A print-designed page: A4, light, colour used only to tell the kinds
    /// of stream apart.
    func pdfHTML(iconPNG: Data?, isDark: Bool = false) -> String {
        let icon = iconPNG.map {
            "<img class=\"icon\" src=\"data:image/png;base64,\($0.base64EncodedString())\" alt=\"\">"
        } ?? ""
        let version = Self.appVersion.isEmpty ? "" : "Version \(Self.esc(Self.appVersion))"

        var html = """
        <!DOCTYPE html>
        <html><head><meta charset="utf-8"><title>\(Self.esc(fileName))</title>
        <style>:root { \(isDark ? Self.pdfDark : Self.pdfLight) }\n\(Self.pdfStyle)</style></head><body>

        <header class="masthead">
          \(icon)
          <div class="brand">
            <div class="app">SwiftMediaInfo</div>
            <div class="kind">Media Report</div>
          </div>
          <div class="stamp">\(Self.esc(dateText))<br>\(version)</div>
        </header>

        <section class="file">
          <h1>\(Self.esc(fileName))</h1>
        """
        if !summary.fileDetails.isEmpty {
            html += "<div class=\"details\">\(summary.fileDetails.map { Self.esc($0) }.joined(separator: "<span class=\"dot\">·</span>"))</div>"
        }
        if !summary.chipGroups.isEmpty {
            html += "<div class=\"chips\">"
            for group in summary.chipGroups {
                for chip in group.chips {
                    html += "<span class=\"chip \(Self.cssClass(group.trackType))\">\(Self.esc(chip))</span>"
                }
            }
            html += "</div>"
        }
        html += "</section>"

        // Each heading travels with what follows it (see `.keep` in the
        // stylesheet): WebKit's print layout ignores `break-after: avoid`, so
        // a heading near the foot of a page was left there on its own while
        // the block it introduces moved to the next.
        if !overviewSections.isEmpty {
            html += "<div class=\"keep\"><h2>Overview</h2><section class=\"overview\">"
            for section in overviewSections {
                html += "<div class=\"card \(Self.cssClass(section.trackType))\"><div class=\"card-title\">\(Self.esc(section.title))</div><table>"
                for row in section.rows {
                    html += "<tr><th>\(Self.esc(row.label))</th><td>\(Self.esc(Self.shortened(row)))</td></tr>"
                }
                html += "</table></div>"
            }
            html += "</section></div>"
        }

        if !trackSections.isEmpty {
            html += "<div class=\"keep\"><h2>Tracks</h2>"
            for (index, section) in trackSections.enumerated() {
                html += "<div class=\"track \(Self.cssClass(section.trackType))\"><div class=\"track-title\">\(Self.esc(section.title))</div><table>"
                for row in section.rows {
                    html += "<tr><th>\(Self.esc(row.label))</th><td>\(Self.esc(row.value))</td></tr>"
                }
                html += "</table></div>"
                // The heading is kept with the first track only.
                if index == 0 { html += "</div>" }
            }
        }

        html += """
        <footer class="colophon">
          <div class="made">Generated by <strong>SwiftMediaInfo</strong>\(Self.appVersion.isEmpty ? "" : " " + Self.esc(Self.appVersion)) · \(Self.esc(dateText))</div>
          <div class="links">
            <a class="button" href="\(ProjectLinks.appPage)"><span class="label">Website</span><span class="url">\(Self.websiteText)</span></a>
            <a class="button" href="\(ProjectLinks.github)"><span class="label">GitHub</span><span class="url">\(Self.githubText)</span></a>
          </div>
        </footer>
        </body></html>
        """
        return html
    }

    /// A long list (57 subtitle tracks) would make one overview card run
    /// off the page. The first eight are enough for an overview; every track
    /// is listed in full under Tracks.
    private static func shortened(_ row: MediaSummary.Row) -> String {
        guard let items = row.items, items.count > 8 else { return row.value }
        return items.prefix(8).joined(separator: ", ") + " and \(items.count - 8) more — all listed under Tracks"
    }
    
    private static func cssClass(_ trackType: String) -> String {
        switch trackType {
        case "Video": return "video"
        case "Audio": return "audio"
        case "Text":  return "text"
        case "Image": return "image"
        case "Menu":  return "menu"
        default:      return "general"
        }
    }

    private static func esc(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }

    /// The page colour behind each palette, painted by PDFRenderer.
    static func pdfPaper(isDark: Bool) -> NSColor {
        isDark
        ? NSColor(srgbRed: 0x14 / 255, green: 0x14 / 255, blue: 0x1d / 255, alpha: 1)
        : .white
    }
    
